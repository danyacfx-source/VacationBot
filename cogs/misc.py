    async def upcoming_birthdays(self, interaction: discord.Interaction):
        birthdays = load_birthdays()
        if not birthdays:
            return await interaction.response.send_message(
                "🎂 Дней рождения пока нет.", ephemeral=True
            )

        now = datetime.now()
        this_year = now.year

        upcoming = []
        for uid, info in birthdays.items():
            try:
                bd = datetime.strptime(info["date"], "%d.%m.%Y")
            except ValueError:
                continue

            bd_this = bd.replace(year=this_year)
            if bd_this < now:
                bd_this = bd.replace(year=this_year + 1)

            days_until = (bd_this - now).days
            upcoming.append((days_until, info["name"], info["date"], uid))

        upcoming.sort(key=lambda x: x[0])

        embed = discord.Embed(
            title="🎂 Ближайшие дни рождения",
            color=discord.Color.pink()
        )

        lines = []
        for days, name, bd_date, uid in upcoming[:10]:
            if days == 0:
                lines.append(f"🎉 **{name}** — **СЕГОДНЯ!**")
            elif days == 1:
                lines.append(f"🔔 **{name}** — **ЗАВТРА!** ({bd_date})")
            else:
                lines.append(f"📅 **{name}** — через **{days}** дн. ({bd_date})")

        embed.description = "\n".join(lines) if lines else "Нет данных."
        await interaction.response.send_message(embed=embed)

