def _detect_ai_provider():
    if config.CUSTOM_API_BASE and config.CUSTOM_API_KEY:
        return "custom"
    if config.OPENROUTER_API_KEY:
        return "openrouter"
    if config.GEMINI_API_KEY:
        return "gemini"
    if config.DEEPSEEK_API_KEY:
        return "deepseek"
    return ""


def _ask_custom(system_prompt, message):
    if not config.CUSTOM_API_BASE or not config.CUSTOM_API_KEY:
        return None, "custom", 0
    url = config.CUSTOM_API_BASE
    if not url.endswith("/chat/completions"):
        url += "/chat/completions"
    model = config.AI_MODEL or config.CUSTOM_API_MODEL
    resp = requests.post(
        url,
        headers={
            "Authorization": f"Bearer {config.CUSTOM_API_KEY}",
            "Content-Type": "application/json",
        },
        json={
            "model": model,
            "messages": [
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": message}
            ],
            "max_tokens": 500,
            "temperature": 1.2
        },
        timeout=60
    )
    if resp.status_code != 200:
        logging.error("Custom AI API error %s: %s", resp.status_code, resp.text[:500])
        return None, "custom", resp.status_code
    data = resp.json()
    try:
        return data["choices"][0]["message"]["content"].strip(), "custom", 200
    except (KeyError, IndexError, TypeError):
        return None, "custom", 0


