def _ask_gemini(system_prompt, message):
    if not config.GEMINI_API_KEY:
        return None, "gemini", 0
    model = config.AI_MODEL or "gemini-2.0-flash"
    url = f"https://generativelanguage.googleapis.com/v1beta/models/{model}:generateContent"
    resp = requests.post(
        url,
        params={"key": config.GEMINI_API_KEY},
        json={
            "system_instruction": {"parts": [{"text": system_prompt}]},
            "contents": [{"parts": [{"text": message}]}],
            "generationConfig": {"maxOutputTokens": 500, "temperature": 1.2}
        },
        timeout=60
    )
    if resp.status_code != 200:
        logging.error("Gemini API error %s: %s", resp.status_code, resp.text[:500])
        return None, "gemini", resp.status_code
    data = resp.json()
    try:
        text = data["candidates"][0]["content"]["parts"][0]["text"].strip()
    except (KeyError, IndexError, TypeError):
        return None, "gemini", 0
    return text, "gemini", 200


def _ask_ai(provider, system_prompt, message):
    if provider == "custom":
        return _ask_custom(system_prompt, message)
    if provider == "openrouter":
        return _ask_openrouter(system_prompt, message)
    if provider == "gemini":
        return _ask_gemini(system_prompt, message)
    return _ask_deepseek(system_prompt, message)


