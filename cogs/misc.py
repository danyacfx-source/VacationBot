    @tasks.loop(minutes=30)
    async def tracemalloc_monitor(self):
        try:
            ch = self.bot.get_channel(config.RAM_LOG_CHANNEL)
            if not ch:
                return

            snapshot = tracemalloc.take_snapshot()
            top_stats = snapshot.statistics('lineno')
            total = sum(stat.size for stat in top_stats)

            lines = [f"**Всего отслежено: {total / (1024 * 1024):.2f} MB**\n"]
            lines.append("```")
            lines.append(f"{'File and line':<70}{'Memory':>10}  {'Blocks':>8}")
            lines.append("-" * 91)

            for stat in top_stats[:20]:
                frame = stat.traceback[0]
                filepath = f"{frame.filename}:{frame.lineno}"
                if len(filepath) > 68:
                    filepath = "..." + filepath[-65:]
                size_mb = stat.size / (1024 * 1024)
                lines.append(f"{filepath:<70}{size_mb:>8.2f}MB  {stat.count:>8}")
            lines.append("```")

            embed = discord.Embed(
                title="Отчёт tracemalloc",
                description="\n".join(lines),
                color=discord.Color.green(),
                timestamp=discord.utils.utcnow(),
            )
            await ch.send(embed=embed)
        except Exception as e:
            logging.error("Ошибка tracemalloc_monitor: %s", e, exc_info=True)

